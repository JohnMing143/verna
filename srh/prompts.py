_REPLY_OPENER = re.compile(r"^(?:好的|当然(?:可以)?|没问题|以下是|下面是)")
_REPLY_TAIL = re.compile(r"\n+(?:[#*\s]*)(?:修改说明|润色说明|优化说明|主要修改|修改要点|改动说明|说明)[：:*].*$", re.S)


def clean_reply(raw: str) -> str:
    """去掉改写回复开头单独一行的助手腔（“好的，以下是……：”）和结尾的“修改说明”，再去掉包在外面的引号。"""
    d = raw.strip()
    first, _, rest = d.partition("\n")
    if rest.strip() and len(first) <= 60 and (_REPLY_OPENER.match(first) or first.rstrip().endswith(("：", ":"))):
        d = rest.strip()
    return _REPLY_TAIL.sub("", d).strip().strip("“”\"").strip()


# 11-10 加：AI 初稿的原文里常带 AI 助手自己的开场白和结尾附言（字数说明、“如需调整……告诉我”），这些不是正文，
# 也不是要保留的信息。只动开头一行和结尾几行，正文中间的一律不动。
_HR_LINE = re.compile(r"^\s*(?:-{3,}|\*{3,})\s*$")
# “如需”不能单独当标记：正文里“如需发票，请在付款时备注”是正常句子，只认“如需调整/修改/告知……”这类附言说法
_META_LINE = re.compile(
    r"字数|约\s*\d+\s*字"
    r"|如需(?:调整|修改|进一步|其他|要|需要|有|更多|补充|告知|改动)"
    r"|(?:可以|随时)告诉我"
    r"|希望(?:这|这些|本文|以上)[^\n]{0,12}(?:有帮助|有用|喜欢)"
    r"|希望(?:对你|对您)(?:有所)?帮助|希望(?:能|可以)?帮到"
    r"|以上(?:就是|内容)"
)
# 附言一般以这些开头（列表符号、加粗标签、“字数/全文约…字/如需/希望/以上内容”或整行括号）；
# 正文里恰好出现“字数”“如需”的句子不算，别把一句话的正文整段删掉
_ATTACH_START = re.compile(r"^\s*(?:[*\-•·]|\*\*|字数|全文|约\s*\d+\s*字|如需|希望|以上(?:就是|内容)|[（(])")


def strip_assistant_meta(text: str) -> str:
    """去掉 AI 助手开场白（开头单独一行的“好的/当然/以下是……”）和结尾附言：
    末尾一条 ---/*** 分隔线之后的全部内容，以及末尾几行里的字数说明、“如需调整请告诉我”这类客服腔。"""
    lines = text.strip().split("\n")
    for i in range(len(lines) - 1, -1, -1):
        if _HR_LINE.match(lines[i]):
            # 11-10 主会话复核改：只有分隔线后面是短附言（≤200 字、带字数/如需调整这类标记）才整段去掉；
            # 正文中间用分隔线分节的（后面还有正文）不切，否则规则核对会看不出候选丢了后半段
            tail = "\n".join(lines[i + 1:]).strip()
            if len(tail) <= 200 and (not tail or _META_LINE.search(tail)):
                lines = lines[:i]
            break
    while lines:
        last = lines[-1].strip()
        if not last:
            lines.pop()
        elif len(last) <= 120 and _ATTACH_START.match(last) and _META_LINE.search(last):
            lines.pop()
        else:
            break
    d = "\n".join(lines).strip()
    first, _, rest = d.partition("\n")
    if rest.strip() and len(first) <= 60 and _REPLY_OPENER.match(first):
        d = rest.strip()
    return d


