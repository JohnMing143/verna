REWRITE_INSTRUCTION = (
    "把下面这段文字改得更好读。信息不增不减，文体和作者的语气不变，写得好的地方不要动。只输出改好的正文。"
)


def rewrite_messages(text: str, instruction: str | None = None) -> list[dict]:
    ins = REWRITE_INSTRUCTION if instruction is None else instruction.strip()
    return [{"role": "user", "content": f"{ins}\n\n{text.strip()}" if ins else text.strip()}]


