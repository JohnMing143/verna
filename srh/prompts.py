def pick_recipe(rng: random.Random) -> str:
    names = list(RECIPES)
    return rng.choices(names, weights=[RECIPES[n][0] for n in names])[0]


def aiify_prompt(text: str, recipe: str, rng: random.Random) -> str:
    style = RECIPES[recipe][1]
    if "{tells}" in style:
        ex = [t.example for t in TELLS if t.example and t.cat != "format"]
        style = style.format(tells="、".join(rng.sample(ex, 5)))
    return f"{style}\n\n{_KEEP}\n\n原文：\n{text.strip()}"


