_COMPILED = [(t, re.compile(t.pattern, re.S if t.name in ("首先其次最后", "一方面另一方面") else 0)) for t in TELLS]


def hits(text: str) -> list[tuple[str, str, int, float]]:
    """返回 [(名字, 类别, 次数, 权重)]，只列命中的。"""
    out = []
    for t, rx in _COMPILED:
        n = len(rx.findall(text))
        if n:
            out.append((t.name, t.cat, n, t.weight))
    return out


# 用户点名讨厌、目标语料里一次都不许出现的说法（筛人写语料时直接整段丢掉）
HARD_BAN = {"不是而是", "不仅仅是更是", "与其不如", "不在于而在于", "重要的不是", "说白了", "底层逻辑",
            "自问自答", "希望有帮助", "助手开场"}


def weighted(text: str) -> float:
    return sum(c * w for _, _, c, w in hits(text))


def banned(text: str) -> list[str]:
    return [name for name, _, _, _ in hits(text) if name in HARD_BAN]


def density(text: str) -> float:
    """每千字加权命中数。0 = 干净；人写好文章一般 < 3；典型 AI 输出 8–30。"""
    n = max(len(re.sub(r"\s", "", text)), 1)
    return round(weighted(text) * 1000 / n, 2)


def sentences(text: str) -> list[str]:
    return [s for s in re.split(r"(?<=[。！？!?；;])|\n+", text) if len(s.strip()) > 1]


def burstiness(text: str) -> float:
    """句长变异系数。人写的长短句交错，一般 > 0.5；AI 腔句子长度很整齐，常 < 0.4。"""
    lens = [len(s.strip()) for s in sentences(text)]
    if len(lens) < 3:
        return 0.0
    return round(statistics.pstdev(lens) / statistics.mean(lens), 3)


def report(text: str) -> dict:
    h = hits(text)
    return {
        "density": density(text),
        "burstiness": burstiness(text),
        "hits": {name: c for name, _, c, _ in h},
    }


